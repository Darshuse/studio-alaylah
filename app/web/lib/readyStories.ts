/** يملأ القالب: يستبدل {الاسم} ويختار الصيغة المناسبة لجنس البطل. */
export function renderStory(text: string, name: string, gender: Gender): string {
  const n = name.trim() || "بطلنا";
  return text
    .replace(/‹([^/›]+)\/([^›]+)›/g, (_m, a: string, b: string) => (gender === "f" ? b : a))
    .replace(/\{الاسم\}/g, n);
}
