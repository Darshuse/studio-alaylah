def f(size,b=False): return ImageFont.truetype(BOLD if b else FONT,size)
def rtl(s):
    return get_display(arabic_reshaper.reshape(s), base_dir='R')
def tx(d,xy,text,font,fill,anchor='ra'):
    d.text(xy,rtl(text),font=font,fill=fill,anchor=anchor)
def block(d, text, y, size=31, color='#17222d', bold=False, gap=13):
    font=f(size,bold); maxw=1050; words=text.split(); lines=[]; cur=''
    for word in words:
        test=(cur+' '+word).strip()
        if d.textbbox((0,0),rtl(test),font=font)[2] > maxw:
            lines.append(cur);cur=word
        else: cur=test
    if cur:lines.append(cur)
    for line in lines:
        tx(d,(1120,y),line,font,color)
        y+=size+gap
    return y
def title(d,t,y):
    d.rounded_rectangle((1040,y+5,1053,y+55),radius=3,fill='#d98f41')
    tx(d,(1018,y),t,f(43,True),'#0c3540')
    return y+74
def page(n, heading, sections):
    im=Image.new('RGB',(W,H),'#ffffff');d=ImageDraw.Draw(im)
    d.rectangle((0,0,W,24),fill='#0c5361');d.rectangle((0,H-25,W,H),fill='#0c5361')
    y=80
    if heading:
        tx(d,(1120,y),heading,f(52,True),'#0c3540');y+=84
    for typ,content in sections:
        if typ=='h': y=title(d,content,y)
        elif typ=='p': y=block(d,content,y)+16
        elif typ=='b':
            d.rounded_rectangle((85,y,1155,y+114),radius=14,fill='#edf6f4')
            y=block(d,content,y+17,29,'#204b50',True)+30
        elif typ=='w':
            d.rounded_rectangle((85,y,1155,y+126),radius=14,fill='#fff4e5')
            y=block(d,content,y+17,28,'#754516',False)+30
        elif typ=='list':
            for v in content:
                d.ellipse((1090,y+13,1102,y+25),fill='#d98f41')
                y=block(d,v,y,29)+5
            y+=10
    tx(d,(620,H-16),f'{n}  |  استوديو حكايات العائلة - تقرير اجتماع استراتيجي',f(15),'white','mm')
    path=TMP/f'p{n}.png';im.save(path);return path

